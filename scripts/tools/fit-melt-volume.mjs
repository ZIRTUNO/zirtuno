/** Solve each Services handoff against its own rendered area. No runtime solver.
 * Run after changing forms, correspondence, transport, or the field equation:
 *   node scripts/tools/fit-melt-volume.mjs
 * The explicit presence override keeps this independent of the generated table.
 */
import fs from "node:fs";
import { loadForms, prepareForms, addBalls } from "../support/melt-sim.mjs";
import { CLOUDS, STAG, N, smooth01 } from "../../lib/webgl/phys.mjs";
import { CONFLUENCE, CONFLUENCE_STAG } from "../../lib/webgl/confluence.mjs";
import { permFor, matchClouds, formPhase, meltDroplet, FORM_SOLIDITY, meltSat } from "../../lib/webgl/melt.mjs";

const RES = Number(process.env.RES ?? 320);
const STEPS = 80;
const forms = await loadForms();
const tables = {};
const droplet = [0, 0, 0, 0];
const area = (f) => f.T.reduce((sum, x) => sum + (x >= 1 ? 1 : 0), 0);

// THE CROSSING (a = 0) IS FITTED TOO, and it is the reason this loop no longer
// starts at 1. It is the melt out of THE CONFLUENCE into the first pillar, and
// it was the ONE handoff on the page with no measured curve: `meltVolumePresence`
// keys on the source cloud, CONFLUENCE is not a CLOUDS member, so the lookup
// could never hit and the melt silently ran the pre-fit symmetric envelope.
// Measured, that envelope does not hold here — the confluence body carries only
// 70% of the web form's area, so the pair has a real 43% growth ramp the shared
// curve does not model, and the rendered area bounced 99 → 120 → 95 → 100% over
// the drain while mass detached and re-merged. That is the loose-speck report.
//
// Its staging differs from a form → form melt in exactly two ways, and both are
// the crossing's own signed-off choreography (lib/webgl/scenes/site.ts):
//   • there is NO form A — S3 has no vector behind it — so only form B is staged;
//   • therefore p = 0 is not an absorbed cloud but the WHOLE PICTURE, and the
//     ramp starts from the confluence body's own area rather than from a form's.
for (let a = 0; a < 7; a++) {
  const b = a + 1;
  const crossing = a === 0;
  const A = crossing ? CONFLUENCE : CLOUDS[a];
  const perm = crossing ? matchClouds(CONFLUENCE, CLOUDS[1]) : permFor(a, b);
  const stag = crossing ? CONFLUENCE_STAG : STAG[a];
  const swA = crossing ? 0 : FORM_SOLIDITY[a];
  const prepare = (p) => {
    const ph = formPhase(p);
    return prepareForms({ forms, a: crossing ? 0 : a, b,
      fa: crossing ? 0 : ph.wA, fb: ph.wB,
      ea: crossing ? 0 : ph.eA, eb: ph.eB, res: RES, n: meltSat(p) });
  };
  // THE RAMP'S TWO ENDS. For a form → form melt both are silhouettes and the
  // cloud is absorbed at each. The crossing's near end is the confluence body
  // ITSELF, rendered at full density with nothing else on the stage — which is
  // what makes its curve open at ~1 instead of at 0.
  const bare = prepare(0);
  const start = crossing
    ? addBalls(bare.T, bare.shield, RES, CONFLUENCE.map((d) => [d[0], d[1], d[2], 1])).lit
    : area(bare);
  const end = area(prepare(1));
  const values = [];
  for (let s = 0; s <= STEPS; s++) {
    const p = s / STEPS;
    // Both endpoints are exact by construction and need no solve: a form → form
    // melt hands its cloud back absorbed (0), the crossing opens on the body it
    // already is (1) and closes absorbed under the pillar (0).
    if (p <= 0) { values.push(crossing ? 1 : 0); continue; }
    if (p >= 1) { values.push(0); continue; }
    const f = prepare(p);
    const target = start + (end - start) * smooth01(p);
    let lo = 0, hi = 1.6;
    for (let step = 0; step < 15; step++) {
      const presence = (lo + hi) / 2;
      const balls = [];
      for (let i = 0; i < N; i++) {
        meltDroplet(droplet, i, A, CLOUDS[b], perm, stag, p,
          swA, FORM_SOLIDITY[b], presence);
        balls.push([...droplet]);
      }
      const got = addBalls(f.T, f.shield, RES, balls, meltSat(p)).lit;
      if (got < target) lo = presence;
      else hi = presence;
    }
    // Automation's returning arc needs a little overlap while its thin
    // skeleton reconnects. The local C-infinity shoulder prevents a detached
    // reappearance without exceeding the larger endpoint's area. This is
    // independently checked by melt-shape's spatial pop/connectivity gate.
    const continuity = a === 3 ? 1 + 0.30 * Math.exp(-Math.pow((p - 0.875) / 0.025, 2)) : 1;
    const density = +((lo + hi) / 2).toFixed(6);
    values.push(+(density * continuity).toFixed(6));
  }
  const key = crossing ? `cross-${b}` : `${a}-${b}`;
  tables[key] = values;
  console.log(`${key}: density ${Math.min(...values).toFixed(3)}..${Math.max(...values).toFixed(3)}`);
}
const output = process.env.OUT ?? "lib/webgl/melt-volume.data.mjs";
fs.writeFileSync(output,
  `// Generated by scripts/tools/fit-melt-volume.mjs at ${RES}x${RES}.\n` +
  `// Actual field area follows a smooth ramp between the two exact forms.\n` +
  `export const MELT_VOLUME = ${JSON.stringify(tables, null, 2)};\n`);
console.log(output);
